#!/usr/bin/env python3
"""Regenerate docs/checks.md from the check registry.

    python scripts/generate_docs.py          # write the file
    python scripts/generate_docs.py --check  # fail if it is out of date (used in CI)
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from mast.analysis import CATEGORIES, SEVERITIES, all_checks  # noqa: E402

TARGET = ROOT / "docs" / "checks.md"

HEADINGS = {
    "bugs": ("Bugs", "Defects that make the code do the wrong thing at runtime. This is the bug hunter."),
    "efficiency": ("Efficiency", "Correct code that does avoidable work — usually an accidental O(n²) or a query per row."),
    "structure": ("Structure", "Size, complexity, duplication and coupling: what makes the code expensive to change."),
    "standards": ("Enterprise standards", "Typed public APIs, real exceptions, real logging, no hidden shared state."),
    "security": ("Security", "The Python-specific footguns that turn into incidents."),
}


def render() -> str:
    checks = all_checks()
    by_category = {category: [c for c in checks if c.category == category] for category in CATEGORIES}
    counts = " · ".join(f"{len(by_category[c])} {c}" for c in CATEGORIES if by_category[c])
    severities = " · ".join(
        f"{sum(1 for c in checks if c.severity == severity)} {severity}" for severity in SEVERITIES
    )

    out = [
        "<!-- Generated by scripts/generate_docs.py — edit the check definitions, not this file. -->",
        "",
        "# Check reference",
        "",
        f"**{len(checks)} checks**: {counts}. By severity: {severities}.",
        "",
        "`mast explain <check-id>` prints the same reasoning in the terminal. Every check can be switched off "
        "per project (`analysis.ignore`) or per line (`# mast: ignore[<check-id>]`) — see "
        "[the analyzer](analyzer.md#turning-a-check-off).",
        "",
        "Severity decides what blocks: **high** findings stop a write and gate the end of a turn by default, "
        "**medium** and **low** are reported for Claude to fix as it works.",
        "",
        "## Index",
        "",
        "| | | |",
        "| --- | --- | --- |",
    ]
    for category in CATEGORIES:
        if not by_category[category]:
            continue
        title = HEADINGS[category][0]
        ids = ", ".join(f"[`{c.id}`](#{_anchor(c.id)})" for c in by_category[category])
        out.append(f"| **{title}** | {len(by_category[category])} | {ids} |")

    for category in CATEGORIES:
        group = by_category[category]
        if not group:
            continue
        title, blurb = HEADINGS[category]
        out += ["", f"## {title}", "", blurb, ""]
        for check in group:
            out += [
                f"### `{check.id}`",
                "",
                f"**{check.title}** · {check.severity}",
                "",
                f"{check.why}",
                "",
                f"**Fix.** {check.fix}",
                "",
            ]
    return "\n".join(out).rstrip() + "\n"


def _anchor(check_id: str) -> str:
    return check_id.replace("/", "")


def main() -> int:
    content = render()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != content:
            print("docs/checks.md is out of date — run `python scripts/generate_docs.py`", file=sys.stderr)
            return 1
        print("docs/checks.md is up to date.")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(content, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(content.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
